#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = ["pyyaml"]
# ///
"""render: the neutral role and skill files, as the files Claude Code reads.

`assistants/*.md` and `skills/*/` are the source. This script writes
`.claude/agents/<role>.md` and `.claude/skills/<name>/` from them, and
`--check` fails when what is on disk is not what the source renders to, so
the rendered files can be committed and can never quietly become the place
where a role is defined.

What a rendered agent file carries:

  tools     the tools the role needs and no others: Read, Glob and Grep
            always; Bash when `may_call` names a command; Write and Edit
            when `writes` is not empty; Skill when it names a skill;
            Agent(<roles>) when it names roles to start
  skills    the role's skills, loaded when the role starts
  the wiki  the two read-only wiki tools, openwiki_search and openwiki_read,
            from the server named `openwiki` in `.mcp.json`, which this
            script also writes: by default this package's own read-only
            server on `openwiki/` (the OpenWiki tool's server can be named
            there in its place)
  hooks     one PreToolUse hook on every tool call: allow.py, which reads
            the role file and blocks what it does not allow
  the body  the role file's front matter set out in words, then its
            instructions unchanged

Usage: render.py            write the rendered files
       render.py --check    fail when the rendered files are missing, stale or have extras
       render.py --selftest
"""
import argparse
import json
import shutil
import sys
import tempfile
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent.parent
NOTICE = ("<!-- Rendered from assistants/{name}.md by runners/claude-code/render.py. Do not edit this file: "
          "edit the role file and render again. `render.py --check` fails when the two differ. -->")
WIKI_TOOLS = ("mcp__openwiki__openwiki_search", "mcp__openwiki__openwiki_read")  # the two read-only wiki tools, from whichever server is named openwiki
MCP = {"mcpServers": {"openwiki": {"command": "uv", "args": ["run", "--script", "mvp/loops/wiki_server.py", "--wiki", "openwiki"]}}}
HOOK = 'uv run --script "$CLAUDE_PROJECT_DIR/runners/claude-code/allow.py" --role {name}'


def load(path: Path) -> tuple:
    text = path.read_text(encoding="utf-8")
    end = text.find("\n---\n", 4)
    if not text.startswith("---\n") or end < 0:
        raise ValueError(f"{path} has no front matter")
    fm = yaml.safe_load(text[4:end])
    if not isinstance(fm, dict):
        raise ValueError(f"{path}: the front matter is not a mapping")
    return fm, text[end + 5:]


def tools_for(fm: dict) -> list:
    calls = [str(c) for c in fm.get("may_call") or []]
    tools = ["Read", "Glob", "Grep", *WIKI_TOOLS]
    if any(not c.startswith(("skill:", "role:")) for c in calls):
        tools.append("Bash")
    if fm.get("writes"):
        tools += ["Write", "Edit"]
    if any(c.startswith("skill:") for c in calls):
        tools.append("Skill")
    roles = [c[5:] for c in calls if c.startswith("role:")]
    if roles:
        tools.append(f"Agent({', '.join(roles)})")
    return tools


def bullets(items) -> str:
    out = []
    for x in items or []:
        if isinstance(x, dict):
            out.append(f"- to {x.get('to')}: {x.get('what')}")
        else:
            out.append(f"- {x}")
    return "\n".join(out) or "- nothing"


def render_agent(name: str, fm: dict, body: str) -> str:
    calls = [str(c) for c in fm.get("may_call") or []]
    skills = [c[6:] for c in calls if c.startswith("skill:")]
    head = {"name": name, "description": str(fm["purpose"]), "tools": ", ".join(tools_for(fm))}
    if skills:
        head["skills"] = skills
    head["hooks"] = {"PreToolUse": [{"matcher": "*", "hooks": [{"type": "command", "command": HOOK.format(name=name)}]}]}
    commands = [f"`uv run {c}`" for c in calls if not c.startswith(("skill:", "role:"))]
    words = [
        "---", yaml.safe_dump(head, sort_keys=False, width=1000, allow_unicode=True).rstrip(), "---", "",
        NOTICE.format(name=name), "",
        "## What the role file allows", "",
        f"You are the {name} assistant of a science factory. You act under the name `agent:{name}` (or `agent:{name}-<suffix>` "
        "when the coordinating assistant gives you one) in every `--by`. Run every command from the repository root. "
        "Each tool call you make is checked against your role file before it runs, and what the file does not allow is blocked.", "",
        "**You may call:** " + (", ".join(commands) or "no commands") + ".", "",
        "**Skills:** " + (", ".join(f"`{s}`" for s in skills) or "none") + ".", "",
        "**Roles you may start:** " + (", ".join(c[5:] for c in calls if c.startswith("role:")) or "none") + ".", "",
        "**You must never see:**", "", bullets(fm.get("must_never_see")), "",
        "**You read:**", "", bullets(fm.get("reads")), "",
        "**You write (path patterns):**", "", bullets(fm.get("writes")), "",
        "**You hand on:**", "", bullets(fm.get("hands_on")), "",
        body.strip(), ""]
    return "\n".join(words)


def rendered(root: Path) -> dict:
    """Every file the runner owns under .claude/, by path from the repository, with its bytes."""
    out = {}
    for path in sorted((root / "assistants").glob("*.md")):
        fm, body = load(path)
        out[f".claude/agents/{path.stem}.md"] = render_agent(path.stem, fm, body).encode()
    out[".mcp.json"] = (json.dumps(MCP, indent=1) + "\n").encode()
    for skill in sorted(p for p in (root / "skills").iterdir() if (p / "SKILL.md").is_file()):
        for f in sorted(q for q in skill.rglob("*") if q.is_file() and "__pycache__" not in q.parts):
            out[f".claude/skills/{skill.name}/{f.relative_to(skill).as_posix()}"] = f.read_bytes()
    return out


def on_disk(root: Path) -> dict:
    out = {}
    if (root / ".mcp.json").is_file():
        out[".mcp.json"] = (root / ".mcp.json").read_bytes()
    for sub in ("agents", "skills"):
        base = root / ".claude" / sub
        if base.is_dir():
            for f in sorted(q for q in base.rglob("*") if q.is_file() and "__pycache__" not in q.parts):
                out[f.relative_to(root).as_posix()] = f.read_bytes()
    return out


def drift(root: Path) -> list:
    want, have = rendered(root), on_disk(root)
    p = [f"{k} is missing: render again" for k in want if k not in have]
    p += [f"{k} is not what the source renders to: it was edited by hand, or the source changed and was not rendered" for k in want if k in have and have[k] != want[k]]
    p += [f"{k} has no source in assistants/ or skills/: a role or a skill defined only in the platform's files is not part of the factory" for k in have if k not in want]
    return p


def write(root: Path) -> int:
    want = rendered(root)
    for sub in ("agents", "skills"):
        shutil.rmtree(root / ".claude" / sub, ignore_errors=True)
    for rel, data in want.items():
        f = root / rel
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_bytes(data)
    return len(want)


def selftest() -> int:
    results = []
    tmp = Path(tempfile.mkdtemp(prefix="render-selftest-")).resolve()
    try:
        for sub in ("assistants", "skills"):
            shutil.copytree(ROOT / sub, tmp / sub, ignore=shutil.ignore_patterns("__pycache__"))
        results.append(("before rendering, the check fails", any("is missing" in q for q in drift(tmp))))
        n = write(tmp)
        results.append(("after rendering, the check passes", n > 0 and drift(tmp) == []))
        agent = (tmp / ".claude/agents/review.md").read_text()
        results.append(("the review role gets no Write outside its pattern and no Agent tool", "tools: Read, Glob, Grep, mcp__openwiki__openwiki_search, mcp__openwiki__openwiki_read, Bash, Write, Edit, Skill\n" in agent and "Agent(" not in agent))
        coord = (tmp / ".claude/agents/coordinating.md").read_text()
        results.append(("the coordinating role gets no Write and may start the three other roles",
                        "tools: Read, Glob, Grep, mcp__openwiki__openwiki_search, mcp__openwiki__openwiki_read, Bash, Agent(analysis, review, curating)\n" in coord))
        results.append(("every rendered role carries the hook that reads its role file",
                        all("allow.py\" --role " + p.stem in p.read_text() for p in (tmp / ".claude/agents").glob("*.md"))))
        results.append(("a rendered role names its source and says not to edit it", "Rendered from assistants/review.md" in agent))
        (tmp / ".claude/agents/review.md").write_text(agent.replace("Write, Edit, Skill\n", "Write, Edit, Skill, WebFetch\n"))
        results.append(("a rendered file edited by hand fails the check", any("not what the source renders to" in q for q in drift(tmp))))
        write(tmp)
        role = tmp / "assistants/analysis.md"
        role.write_text(role.read_text().replace('  - "mvp/loops/explore.py look"\n', ""))
        results.append(("a role file changed without rendering fails the check", any(".claude/agents/analysis.md is not what" in q for q in drift(tmp))))
        write(tmp)
        (tmp / ".claude/agents/helper.md").write_text("---\nname: helper\ndescription: defined only here\n---\n")
        results.append(("a role defined only in the platform's files fails the check", any("helper.md has no source" in q for q in drift(tmp))))
        write(tmp)
        (tmp / "skills/review-work/SKILL.md").write_text((tmp / "skills/review-work/SKILL.md").read_text() + "\nMore.\n")
        results.append(("a skill changed without rendering fails the check", any("review-work/SKILL.md is not what" in q for q in drift(tmp))))
        write(tmp)
        (tmp / ".claude/skills/extra").mkdir()
        (tmp / ".claude/skills/extra/SKILL.md").write_text("---\nname: extra\ndescription: x\n---\n")
        results.append(("a skill defined only in the platform's files fails the check", any("extra/SKILL.md has no source" in q for q in drift(tmp))))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    failed = [n for n, good in results if not good]
    for n in failed:
        print("FAIL:", n)
    print(f"selftest: {'PASS' if not failed else 'FAIL'} ({len(results) - len(failed)} of {len(results)})")
    return 0 if not failed else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        return selftest()
    if a.check:
        found = drift(ROOT)
        for q in found:
            print("render --check:", q)
        print(f"render --check: {'FAIL' if found else 'PASS'} ({len(rendered(ROOT))} rendered files)")
        return 1 if found else 0
    print(f"rendered {write(ROOT)} files: .claude/agents, .claude/skills and .mcp.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
